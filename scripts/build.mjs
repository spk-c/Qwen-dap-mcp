import { copyFileSync, existsSync, mkdirSync, readdirSync, rmSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';

const root = fileURLToPath(new URL('../', import.meta.url));
const source = join(root, 'src');
const output = join(root, 'dist');
if (!existsSync(source)) throw new Error('src/ is missing; cannot build.');
function copySources(from, to) {
  mkdirSync(to, { recursive: true });
  for (const entry of readdirSync(from, { withFileTypes: true })) {
    const input = join(from, entry.name);
    const destination = join(to, entry.name);
    if (entry.isDirectory()) copySources(input, destination);
    else if (entry.isFile() && entry.name.endsWith('.js')) copyFileSync(input, destination);
  }
}
// A clean build must not reuse declarations or sourcemaps generated by the
// unavailable original TypeScript sources.
rmSync(output, { recursive: true, force: true });
copySources(source, output);
execFileSync(process.execPath, [join(root, 'node_modules', 'typescript', 'bin', 'tsc'), '--project', join(root, 'tsconfig.json')], { cwd: root, stdio: 'inherit' });
console.log('Built dist/ from editable JavaScript and regenerated TypeScript declarations.');
